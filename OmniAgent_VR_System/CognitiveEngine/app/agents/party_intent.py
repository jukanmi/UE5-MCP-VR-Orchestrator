"""플레이어 발화의 파티 의도(합류 초대 / 해산) 키워드 판정 — 키워드 상수의 단일 소스.

파인튜닝 SLM 은 학습 의도표에 "같이 가자" 가 Follow 로 묻혀 있어 JoinParty/LeaveParty 를 내지 못한다.
그래서 서버가 발화 키워드로 (1) 프롬프트 힌트 (2) 사후 액션 보정 (3) 파티 어휘 꼬리 조건부 부착을 한다.
세 곳 모두 이 모듈의 detect_party_intent 만 본다.

오탐 규칙(모두 detect_party_intent 안에서 적용):
- 키워드 앞은 한글·영문·숫자가 아니어야 한다("스팀" 속 "팀" 제외).
- "일행/동료/팀/파티" 명사 단독은 초대가 아니고, 합류 동작과 결합("일행이 되", "파티에 들어")할 때만 초대.
- 키워드 바로 뒤에 부정("하지 마", "안 해", "싫", "말자")이 오면 제외.
- "같이/함께 가자" 뒤 같은 문장에 목적지 조사(으로/로/에/까지/쪽) 낱말이 오면 이동 요청이라 초대 아님.
"""

import re

# 키워드 앞은 한글·영문·숫자가 아니어야 한다(왼쪽 경계).
_L = r"(?<![가-힣A-Za-z0-9])"

# 해산이 먼저 평가된다: "일행에서 빠져" 는 초대 쪽 낱말도 포함하므로. "해산물" 제외.
# "헤어지기 전에" 같은 명사형은 제외하고 청유·명령·의지형만.
_DISMISS_RE = re.compile(
    _L
    + r"(?:해산(?!물)"
    + r"|헤어(?:지자고?|지죠|질래|지세요|집시다|져(?:라|요|줘)?)(?![가-힣])"
    + r"|그만\s*따라"
    + r"|파티\s*탈퇴"
    + r"|(?:일행|파티|팀)에서\s*(?:빠|나가|나와))"
)

# "따라와"/"따라 와" 는 초대가 아니다(기존 Follow 유지). 이동형 "같이 가자" 는 move 그룹 — 목적지 검사 대상.
# 합류는 (?=...) 로 동사 어미를 소비하지 않아 뒤따르는 "하지 마" 를 부정 검사가 볼 수 있다.
_INVITE_RE = re.compile(
    _L
    + r"(?:합류(?=\s*(?:하|해|할|합|시켜))"
    + r"|일행(?:이\s*[되돼]|으로|에\s*(?:들어|끼|합류)|\s*(?:하자|할래|할까|해))"
    + r"|동료(?:가\s*[되돼]|로)"
    + r"|파티(?:에\s*(?:들어|끼|합류)|\s*(?:하자|할래))"
    + r"|팀(?:에\s*(?:들어|끼)|이\s*[되돼]|\s*(?:하자|할래))"
    + r"|(?P<move>(?:같이|함께)\s*(?:가(?:자고?|줘|줄래|요|라|면)?|갈래|갈까|다니(?:자|면|고|줘|세요)?)(?![가-힣])))"
)

_NEG_RE = re.compile(r"하지\s*[마말]|안\s*[해할하돼되]|싫|말자|말고|못\s*[해하]")
_DEST_RE = re.compile(r"[가-힣A-Za-z0-9]+(?:으로|로|에|까지|쪽)(?![가-힣])")


def _tail(text: str, end: int, n: int) -> str:
    """키워드 뒤 n 자, 같은 문장(. ? ! 전)까지."""
    return re.split(r"[.?!。]", text[end : end + n], maxsplit=1)[0]


def detect_party_intent(text: str) -> str:
    """발화에서 파티 의도를 판정한다. 반환: "dismiss" | "invite" | "" (해당 없음)."""
    if not text:
        return ""
    for m in _DISMISS_RE.finditer(text):
        if not _NEG_RE.search(_tail(text, m.end(), 8)):
            return "dismiss"
    for m in _INVITE_RE.finditer(text):
        if _NEG_RE.search(_tail(text, m.end(), 8)):
            continue
        if m.group("move") and _DEST_RE.search(_tail(text, m.end(), 15)):
            continue  # "같이 가자, 저 상점으로" — 이동 요청
        return "invite"
    return ""
